---------------------------------------------------------------
-- TransMotion速度说明
-- TransMotion用于过渡点前进/后退。速度参数由调用方传入：带载路径通常传LDAcc/LDVel，空载回程通常传NLDAcc/NLDVel。
-- 这里不要再写死30/20/10等速度，否则界面设置为100也不会真正生效。
-- TransMotion speed note
-- TransMotion is used for forward/backward transition points. Speed is passed by the caller: loaded paths normally use LDAcc/LDVel, unloaded return paths normally use NLDAcc/NLDVel.
-- Do not hard-code 30/20/10 here; otherwise UI speed values such as 100 will not actually take effect.
---------------------------------------------------------------
local function TransMotion(CPoint, CDir, Acc, Vel)
    local SD = 1
    local ED = CPoint.Paras.TransNum
    if (CDir == Dir.Backward) then
        SD = CPoint.Paras.TransNum
        ED = 1
    end

    local TAcc = Acc or NLDAcc
    local TVel = Vel or NLDVel
    local MotionPath = nil

    -- src3必须提供方向对应的完整过渡路径。
    -- 禁止静默退回MotionPoint，否则src3路径生成异常时机器人仍会运行，
    -- 并可能重新使用未经连续化处理的J6路径。
    if CDir == Dir.Forward then
        MotionPath = CPoint.ForwardMotionPoint
    elseif CDir == Dir.Backward then
        MotionPath = CPoint.BackwardMotionPoint
    end

    if type(MotionPath) ~= "table" then
        Alarm("Trajet de transition invalide !", ErrorMessage.Type.PointErr)
        return false
    end

    for i = SD, ED, CDir do
        local TPoint = MotionPath[i]
        if (type(TPoint) ~= "table") or (TPoint.joint == nil) then
            Alarm("Point de transition invalide !", ErrorMessage.Type.PointErr)
            return false
        end

        if CPoint.Paras.Mode == MotionType.Part then
            local PartVel = TVel
            if CDir == Dir.Forward then
                PartVel = TVel * 0.5
            end
            MovL(TPoint, { a = TAcc, v = PartVel, cp = 100 })
        else
            MovJ(TPoint, { a = TAcc, v = TVel, cp = 100 })
        end
    end
    return true
end
