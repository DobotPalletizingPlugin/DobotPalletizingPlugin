    if (PalletSuckerFunction == SuckerCfg.Type.SSingle) then
        local ErrA = 0
        local ErrB = 0
        SetTool485(Communication.Sucker.Tcp.BaudRate, Communication.Sucker.Tcp.Parity, Communication.Sucker.Tcp.StopBit)
        ErrA, Communication.Sucker.Tcp.Socket = TCPCreate(false, Communication.Sucker.Tcp.Ip,
            Communication.Sucker.Tcp.Port) -- 创建TCP客户端
        ErrB = TCPStart(Communication.Sucker.Tcp.Socket, 5) -- 建立TCP连接
        if ErrA ~= 0 or ErrB ~= 0 then
            Alarm("Échec de l’initialisation de la ventouse !", ErrorMessage.Type.IPErr)
        else
            LogInfo("Création du client TCP de la ventouse réussie !")
        end
    else
        SuckerControll(SuckerCfg.Port, OFF, math.abs(PalletSuckerFunction))
        if (PalletSuckerFunction ~= SuckerCfg.Type.SSingle) then
            SuckerSafeIO(OFF)
        end
        if PartCfg.Enable then
            IORes(PartCfg.Port.Mode, PartCfg.Port.A, OFF)
        end

        if SuckerCfg.Dete.VacuumBreak.Enable == 1 then
            SuckerControll(SuckerCfg.Dete.VacuumBreak, OFF, math.abs(PalletSuckerFunction))
        end
    end
    LogInfo("Initialisation de la ventouse réussie !")
end
