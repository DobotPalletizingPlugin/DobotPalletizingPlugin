-- 主程序
InitStorageMode()
InitModbus()
-- 必须在InitFSM/ACK/隔板不足判断前同步，否则界面和报警逻辑仍可能读取到旧的0。
SyncAllPartitionRemainBySensor(true)
InitFSM()
InitPallet()
while true do
    Wait(Time.Thread.s0)
    MotionFSM()
end
