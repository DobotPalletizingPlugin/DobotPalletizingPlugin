                ModbusCreate(Communication.Lifting.Brand.LINAK.Modbus.Ip, Communication.Lifting.Brand.LINAK.Modbus.Port)
            LogInfo("Tentative de connexion Modbus TCP à la colonne LINAK sur %s:%d !",
                Communication.Lifting.Brand.LINAK.Modbus.Ip, Communication.Lifting.Brand.LINAK.Modbus.Port)
        end
    }
    local switch_mode = SwitchCommMode[Communication.Lifting.Mode]
    if switch_mode then
        switch_mode()
    else
        Alarm("CommMode est incorrect !", ErrorMessage.Type.WorkingDataErr)
    end
    if (Err == 0) then
        LogInfo("Initialisation de la communication terminée !")
    else
        Alarm("Échec de l’initialisation de la communication !", ErrorMessage.Type.LinkErr)
    end

    local SwitchCommInitMode = {
        [LiftingType.EWELLIX] = function()
            LogInfo("Création du client TCP réussie !")
            Err = EWLInit()
            Err, CurrentHeight = EWLGetPosition()
