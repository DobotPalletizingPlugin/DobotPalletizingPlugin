-- 入口只负责分流，普通箱和隔板动作互不修改。
local function PTPMotion(PalletNumber, CPoint, CQueue)
    local CPose = nil

    if PalletNumber.Mode == WorkType.Pallet then
        if CPoint.Paras.Mode == MotionType.Part then
            CPose = PartitionPalletMotion(PalletNumber, CPoint)
        else
            CPose = BoxPalletMotion(PalletNumber, CPoint, CQueue)
        end
    else
        CPose = DepalletMotion(PalletNumber, CPoint)
    end

    if (CPose == nil) or (CPose.pose == nil) then
        return
    end

    UpdatePartData(PalletNumber, CPoint)
    PrePallet = PalletNumber.Pallet
    PrePoseHeight = CPose.pose[3] + CPoint.Paras.LH
end

local function PreMotion(PalletNumber, CQueue)
    local CPoint = CQueue:Peek()
    if (CPoint == nil) then
        Alarm("Erreur du point PreMotion !", ErrorMessage.Type.PointErr)
        return nil
    end

    if (CPoint.Paras ~= nil) and (CPoint.Paras.Mode == MotionType.Part) then
        -- 隔板动作必须先检查DI21，再从队列Pop；避免隔板不足报警后动作被提前消费。
        -- For partition motion, check DI21 before Pop; otherwise an empty-magazine alarm may consume the queued partition motion.
        -- 这里不再先调用SyncPartitionRemainBySensor()，避免同一笔隔板动作前重复防抖等待。
        -- Do not call SyncPartitionRemainBySensor() here to avoid duplicate debounce before the same partition motion.
        if CheckPartitionRemainBeforeMotion(PalletNumber, CPoint) == false then
            return nil
        end
    end

    CPoint = CQueue:Pop()
    if (CPoint == nil) then
        Alarm("Erreur du point PreMotion !", ErrorMessage.Type.PointErr)
        return nil
    end

    if (CPoint.Paras.ErrIndex > 0) then
        GetPointInfo(PalletNumber, CPoint)
    end
    if (PalletNumber.Partition.Enable == true) then
        PalletNumber.Partition.Mode = CPoint.Paras.Mode
    end
    AdjustLiftingHeight(CPoint.Paras.LH)
    return CPoint
end
---------------------------------------------------------------
-- 执行运动队列。
-- 外层循环等待当前栈板仍然处于可运行状态；
-- 内层循环等待取料许可、缠膜完成、隔板动作许可等条件满足后，调用PTPMotion执行一次完整取放。
local function ExecuteMotion(PalletNumber, CQueue)
    while true do
        Wait(Time.Thread.s0)
        if (PalletNumber.State.Done == true or PalletNumber.Pallet ~= Pallet or Pallet == Idle) then
            break
        end
        if (CQueue:IsEmpty() == false) then
            local CPoint = PreMotion(PalletNumber, CQueue)
            if CPoint == nil then
                -- PreMotion may return nil when DI21 reports no partition before Pop. Keep the queue intact and retry after pause/recovery.
                Wait(Time.Thread.s0)
            else
                while true do
                    FilmMotion()
                    GetLiftingHeight(CPoint.Paras.LH)
                    -- 隔板动作不依赖输送线来料许可；普通箱子必须同时满足栈板就绪、取料信号就绪、缠膜完成。
                    if (CPoint.Paras.Mode == MotionType.Part) or
                        ((PalletNumber.State.StateReady == true) and (SignalReady == true) and (FilmDone == true)) then
                        LogInfo("La palette %s est en cours de traitement !", (Pallet == Left) and "gauche" or "droite")
                        SignalReady = false
                        PTPMotion(PalletNumber, CPoint, CQueue)
                        if (SignalReady == false) then
                            MotionDone = true
                        end
                        if (StateMachine == FSMType.DLR) then
                            return
                        else
                            break
                        end
                    end
                    Wait(Time.Thread.s0)
                end
            end
        end
    end
end
---------------------------------------------------------------
-- 获取运动状态
local function GetMotionFSM(PalletNumber, CQueue)
    if (PalletNumber.State.Init == true) then
        ExecuteMotion(PalletNumber, CQueue)
        if (SimulateMode == 1) or (AgingMode == 1) then
            if (StateMachine == FSMType.SLR or StateMachine == FSMType.DLR) then
                if FirstPallet.State.Done == true and SecondPallet.State.Done == true then
                    FirstPallet.State.SReset = true
                end
            else
                PalletNumber.State.SReset = true
            end
        end
    end
end
---------------------------------------------------------------
-- 主状态机调度。
-- 单输送模式下直接执行当前Pallet对应队列；
-- 双输送模式下只有SignalReady为true时才调度，避免两个队列同时抢占机器人。
local function MotionFSM()
    local SwitchFSM = {
        [Idle] = function()
        end,
        [Left] = function()
            GetMotionFSM(FirstPallet, FQueue)
        end,
        [Right] = function()
            GetMotionFSM(SecondPallet, SQueue)
        end
    }

    if (StateMachine ~= FSMType.DLR) or (StateMachine == FSMType.DLR and SignalReady == true) then
        local switch_mode = SwitchFSM[Pallet]
        if switch_mode then
            switch_mode()
        else
            Alarm("SwitchFSM est incorrect !", ErrorMessage.Type.WorkingDataErr)
        end
    end
end
