    if switch_mode then
        switch_mode()
    else
        Alarm("CommMode est incorrect !", ErrorMessage.Type.WorkingDataErr)
    end
    if (Err == 0) then
        LogInfo("Initialisation de la communication terminée !")
    else
        Alarm("Échec de l’initialisation de la communication !", ErrorMessage.Type.LinkErr)
    end

    local SwitchCommInitMode = {
        [LiftingType.EWELLIX] = function()
            LogInfo("Création du client TCP réussie !")
            Err = EWLInit()
            Err, CurrentHeight = EWLGetPosition()
            if (Communication.Lifting.StopFlag == true) then
                Communication.Lifting.StopFlag = false
                Err, CurrentHeight = EWLGetPosition()
            end
        end,
        [LiftingType.GeMinG] = function()
            LogInfo("Création du client Modbus RTU réussie !")
            SV660CInit()
            SV660CEnable(1)
            CurrentHeight = SV660CGetPostion()[1]
            if CurrentHeight == nil then
                Err = 1
            else
                CurrentHeight = 0.1 * CurrentHeight
            end
        end,
        [LiftingType.ZT3ILC] = function()
            LogInfo("Création du client Modbus réussie !")
            ZC01Init()
            ZC01Enable(1)
            CurrentHeight = ZC01GetPostion()[1]
            if CurrentHeight == nil then
                Err = 1
            else
                CurrentHeight = ConvertFloat(CurrentHeight)
