-- 隔板余量传感器检测：放置隔板后检测料仓是否还有隔板
-- DI = ON/1：认为料仓有隔板，恢复默认隔板数量，并写入Modbus/SetVal
-- DI ON/1 means partitions are available; restore the default partition count and write it to Modbus/SetVal
-- DI = OFF/0：认为料仓无隔板，将剩余隔板数量置为0，并写入Modbus/SetVal
-- DI OFF/0 means no partitions are available; set remaining partition count to 0 and write it to Modbus/SetVal
local function CheckPartitionRemainSensor(PalletNumber, CPoint)
    if (CPoint == nil) or (CPoint.Paras == nil) then
        return
    end

    if (CPoint.Paras.Mode ~= MotionType.Part) or (PalletNumber.Mode ~= WorkType.Pallet) then
        return
    end

    if (PartSensorCfg == nil) or (PartSensorCfg.Enable ~= true) then
        return
    end

    if (PartSensorCfg.Port == nil) or (PartSensorCfg.Port.A == nil) then
        LogWarn("L’entrée DI du capteur de présence des intercalaires n’est pas configurée !")
        return
    end

    if SimulateMode == 1 then
        return
    end

    local DelayTime = PartSensorCfg.DelayTime or 0
    local SensorState = CheckDIRes(PartSensorCfg.Port.Mode, PartSensorCfg.Port.A)

    if DelayTime > 0 then
        Wait(DelayTime)
        SensorState = CheckDIRes(PartSensorCfg.Port.Mode, PartSensorCfg.Port.A)
    end

    if SensorState == ON then
        PalletNumber.Partition.RePartNum = PalletNumber.ProcessNum.PartitionNum
        WritePartNum(PalletNumber)
        LogInfo(
            "Le capteur de présence des intercalaires DI%s est actif. Restauration du nombre d’intercalaires par défaut et écriture Modbus : %s.",
            tostring(PartSensorCfg.Port.A), tostring(PalletNumber.Partition.RePartNum))
    else
        PalletNumber.Partition.RePartNum = 0
        WritePartNum(PalletNumber)
        LogWarn("Le capteur de présence des intercalaires DI%s est inactif. Le nombre d’intercalaires restants est défini à 0 et écrit dans Modbus.",
            tostring(PartSensorCfg.Port.A))
    end
end
---------------------------------------------------------------
-- 隔板动作开始前检测：如果传感器已经确认无隔板，则不再继续执行取隔板动作
local function CheckPartitionRemainBeforeMotion(PalletNumber, CPoint)
    if (CPoint == nil) or (CPoint.Paras == nil) then
        return true
    end

    if (CPoint.Paras.Mode ~= MotionType.Part) or (PalletNumber.Mode ~= WorkType.Pallet) then
        return true
    end

    if (PartSensorCfg == nil) or (PartSensorCfg.Enable ~= true) then
        return true
    end

    if (PartSensorCfg.Port == nil) or (PartSensorCfg.Port.A == nil) then
        LogWarn("L’entrée DI du capteur de présence des intercalaires n’est pas configurée !")
        return true
    end

    if SimulateMode == 1 then
        return true
    end

    local DelayTime = PartSensorCfg.DelayTime or 0
    local SensorState = CheckDIRes(PartSensorCfg.Port.Mode, PartSensorCfg.Port.A)

    if DelayTime > 0 then
        Wait(DelayTime)
        SensorState = CheckDIRes(PartSensorCfg.Port.Mode, PartSensorCfg.Port.A)
    end

    if SensorState == OFF then
        PalletNumber.Partition.RePartNum = 0
        WritePartNum(PalletNumber)
        LogWarn("Le capteur de présence des intercalaires DI%s est inactif avant le mouvement. Le nombre d’intercalaires restants est défini à 0.",
            tostring(PartSensorCfg.Port.A))
        Alarm("Le magasin d’intercalaires est vide !", ErrorMessage.Type.PartErr)
        return false
    end

    -- 当前传感器检测到有隔板时，强制恢复默认数量，并写入Modbus/SetVal。
    -- 这样即使之前被写成0，补充隔板后也能恢复显示值。
    if PalletNumber.Partition.RePartNum ~= PalletNumber.ProcessNum.PartitionNum then
        PalletNumber.Partition.RePartNum = PalletNumber.ProcessNum.PartitionNum
        WritePartNum(PalletNumber)
        LogInfo(
            "Le capteur de présence des intercalaires DI%s est actif avant le mouvement. Restauration du nombre d’intercalaires par défaut et écriture Modbus : %s.",
            tostring(PartSensorCfg.Port.A), tostring(PalletNumber.Partition.RePartNum))
    end

    return true
end
