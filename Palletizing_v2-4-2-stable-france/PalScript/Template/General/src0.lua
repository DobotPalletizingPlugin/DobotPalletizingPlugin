-- 计算偏心工具。
-- 多吸盘抓多个箱子时，实际负载质心会偏离工具中心。
-- 这里根据吸盘模式和当前仍然吸住的箱子数量，选择对应偏心工具数据，用于SetPayload。
local function CalcEccTool(PalletNumber, Sucker, BoxNum)
    local CTool = {}
    local PlaceNum = math.abs(PalletSuckerFunction)
    if (PlaceNum == BoxNum) then
        CTool = CalcTool(PalletNumber.Coordinate.ToolNum, 0, {0, 0, 0, 0, 0, 0})
    else
        local Ecc = {}
        local EccTool = {}
        local EccData = {}
        Ecc, EccTool, EccData = GetPalletTool(PalletName, ToolType.Ecc)
        local EccLength = {}

        if (Sucker ~= -1) then
            EccLength = (PlaceNum - 1) * EccTool[2][1]
        else
            EccLength = (PlaceNum - 1) * EccTool[3][1]
        end

        local SwitchSucker = {
            [SuckerCfg.Type.Double] = function()
                EccTool[2][1] = EccTool[1][1] + EccLength * math.cos(EccTool[1][6] / 180 * math.pi)
                EccTool[2][2] = EccTool[1][2] + EccLength * math.sin(EccTool[1][6] / 180 * math.pi)
                CTool = DeepCopy(EccTool[2])
            end,
            [SuckerCfg.Type.Triple] = function()
                CTool = CalcTool(PalletNumber.Coordinate.ToolNum, 0, {0, 0, 0, 0, 0, 0})
            end,
            [SuckerCfg.Type.Quadruple] = function()
                CTool = CalcTool(PalletNumber.Coordinate.ToolNum, 0, {0, 0, 0, 0, 0, 0})
            end
        }

        local switch_mode = SwitchSucker[PlaceNum]
        if switch_mode then
            switch_mode()
        else
            Alarm("Le type de ventouse est incorrect !", ErrorMessage.Type.WorkingDataErr)
        end
    end

    LogInfoTable("CTool:", CTool)
    return CTool
end

---------------------------------------------------------------
-- 打开吸盘。
-- 普通箱体仅通过SuckerCfg.Port配置控制真空，并保留阶梯式payload预载。
-- 隔板仅通过PartCfg.Port配置控制独立真空，不使用普通箱吸盘或释放信号。
---------------------------------------------------------------
local function OpenSucker(PalletNumber, CPoint, CIndex)
    local BoxNum = 0
    local CTool = {}

    local SwitchOpenSucker = {
        [MotionType.Norm] = function()
            if (PalletNumber.Mode == WorkType.Pallet) then
                -- 本项目固定：单吸单放。
                BoxNum = 1
                CTool = CalcEccTool(PalletNumber, CPoint.Paras.Sucker, BoxNum)

                local BoxWeight = PalletNumber.BoxProperty.BoxWeight
                local Weight30 = ToolWeight + 0.30 * BoxWeight
                local Weight50 = ToolWeight + 0.50 * BoxWeight
                local Weight75 = ToolWeight + 0.75 * BoxWeight
                local FullWeight = ToolWeight + BoxWeight
                local PayloadCenter = {CTool[1], CTool[2], 0.5 * (CTool[3] + PalletNumber.BoxProperty.BoxHigh)}

                -- 打开前端配置的主真空输出。
                IORes(SuckerCfg.Port.Mode, SuckerCfg.Port.A, ON)
                Wait(50)

                SetPayload(Weight30, PayloadCenter)
                LogInfo("Précharge de prise à 30 %% après activation du vide. Poids : %s", Weight30)
                Wait(50)

                SetPayload(Weight50, PayloadCenter)
                LogInfo("Précharge de prise à 50 %% après activation du vide. Poids : %s", Weight50)
                Wait(50)

                SetPayload(Weight75, PayloadCenter)
                LogInfo("Précharge de prise à 75 %% après activation du vide. Poids : %s", Weight75)

                -- 前面已等待150ms，总真空建立时间保持1000ms。
                Wait(850)
                VerifySuckerDO(SuckerCfg.Port, SuckerCfg.Port.A, ON)
                SuckerSafeIO(OFF)

                SetPayload(FullWeight, PayloadCenter)
                LogInfo("Charge utile de prise à 100 %% après la temporisation du vide. Poids : %s", FullWeight)
                Wait(Time.Pick.In)
            else
                Alarm("Cette fonction OpenSucker personnalisée est réservée au mode de palettisation !", ErrorMessage.Type.WorkingDataErr)
            end
        end,

        [MotionType.Part] = function()
            -- 隔板必须使用前端配置的独立PartCfg端口（现场为DO16）。
            if (PartCfg.Enable ~= true) then
                Alarm("La ventouse d’intercalaire n’est pas activée !", ErrorMessage.Type.WorkingDataErr)
                return
            end

            IORes(PartCfg.Port.Mode, PartCfg.Port.A, ON)
            Wait(Time.Pick.In)

            CTool = CalcEccTool(PalletNumber, CPoint.Paras.Sucker, PalletSuckerFunction)
            SetPayload(PalletNumber.ProcessNum.PartitionWeight + ToolWeight, {CTool[1], CTool[2], 0.5 * CTool[3]})
        end
    }

    local switch_mode = SwitchOpenSucker[CPoint.Paras.Mode]
    if switch_mode then
        switch_mode()
        LogInfo("Activation de la ventouse réussie !")
    else
        Alarm("Erreur OpenSucker. Veuillez vérifier la ventouse !", ErrorMessage.Type.WorkingDataErr)
    end
end
---------------------------------------------------------------
-- 关闭吸盘 / 释放物料。
-- 普通箱：关闭配置的真空输出；如前端启用释放信号，则只通过
-- SuckerCfg.Dete.VacuumBreak配置输出破真空，绝不写死具体DO号。
-- 隔板：只关闭PartCfg独立真空并等待自然飘落，不使用破真空。
---------------------------------------------------------------
local function CloseSucker(PalletNumber, CPoint, CIndex)
    local CTool = {}
    if ((CPoint.Paras.Sucker ~= -1) or (CPoint.Paras.Sucker == -1 and CIndex == PalletSuckerFunction)) then
        CTool = CalcTool(PalletNumber.Coordinate.ToolNum, 0, {0, 0, 0, 0, 0, 0})
    else
        CTool = CalcEccTool(PalletNumber, CPoint.Paras.Sucker, CIndex)
    end

    local Weight = (PalletSuckerFunction - CIndex) * PalletNumber.BoxProperty.BoxWeight + ToolWeight
    local ReleasePayloadDelay = 50
    local PayloadUpdated = false

    local function UpdatePayloadAfterRelease()
        if PayloadUpdated == false then
            SetPayload(Weight, {CTool[1], CTool[2], 0.5 * CTool[3]})
            LogInfo("Charge utile après relâchement : %s", Weight)
            PayloadUpdated = true
        end
    end

    local function WaitReleaseAndUpdatePayload()
        local DelayTime = ReleasePayloadDelay
        if Time.Place.In < DelayTime then
            DelayTime = Time.Place.In
        end
        if DelayTime > 0 then
            Wait(DelayTime)
        end
        UpdatePayloadAfterRelease()
        if Time.Place.In > DelayTime then
            Wait(Time.Place.In - DelayTime)
        end
    end

    local function SetSingleReleaseOutput(CIndex, State)
        local Port = SuckerCfg.Dete.VacuumBreak
        if CIndex == 1 then
            IORes(Port.Mode, Port.A, State)
        elseif CIndex == 2 then
            IORes(Port.Mode, Port.B, State)
        elseif CIndex == 3 then
            IORes(Port.Mode, Port.C, State)
        elseif CIndex == 4 then
            IORes(Port.Mode, Port.D, State)
        end
    end

    local SwitchCloseSucker = {
        [MotionType.Norm] = function()
            local ReleaseEnabled = (SuckerCfg.Dete.VacuumBreak.Enable == 1)

            if (CPoint.Paras.Sucker == -1) then
                if (PalletNumber.Mode == WorkType.Pallet) then
                    -- 多吸单放：只关闭当前箱对应的真空路。
                    if CIndex == 1 then
                        IORes(SuckerCfg.Port.Mode, SuckerCfg.Port.A, OFF)
                    elseif CIndex == 2 then
                        IORes(SuckerCfg.Port.Mode, SuckerCfg.Port.B, OFF)
                    elseif CIndex == 3 then
                        IORes(SuckerCfg.Port.Mode, SuckerCfg.Port.C, OFF)
                    elseif CIndex == 4 then
                        IORes(SuckerCfg.Port.Mode, SuckerCfg.Port.D, OFF)
                    end
                    SuckerSafeIO(ON)

                    if ReleaseEnabled then
                        SetSingleReleaseOutput(CIndex, ON)
                        WaitReleaseAndUpdatePayload()
                        SetSingleReleaseOutput(CIndex, OFF)
                        return
                    end
                else
                    SuckerControll(SuckerCfg.Port, OFF, math.abs(PalletSuckerFunction))
                    SuckerSafeIO(ON)

                    if ReleaseEnabled then
                        SuckerControll(SuckerCfg.Dete.VacuumBreak, ON, math.abs(PalletSuckerFunction))
                        WaitReleaseAndUpdatePayload()
                        SuckerControll(SuckerCfg.Dete.VacuumBreak, OFF, math.abs(PalletSuckerFunction))
                        return
                    end
                end
            elseif (PalletSuckerFunction == SuckerCfg.Type.SSingle and CPoint.Paras.Sucker == 0) then
                TCPWrite(Communication.Sucker.Tcp.Socket, Communication.Sucker.Command.VacuumOff)
            else
                local ReleaseNum = math.ceil(0.5 * CPoint.Paras.Sucker) + 1
                SuckerControll(SuckerCfg.Port, OFF, ReleaseNum)
                SuckerSafeIO(ON)

                if ReleaseEnabled then
                    SuckerControll(SuckerCfg.Dete.VacuumBreak, ON, ReleaseNum)
                    WaitReleaseAndUpdatePayload()
                    SuckerControll(SuckerCfg.Dete.VacuumBreak, OFF, ReleaseNum)
                    return
                end
            end

            -- 未启用释放信号时，只等待物料自然脱离并更新payload。
            WaitReleaseAndUpdatePayload()
        end,

        [MotionType.Part] = function()
            -- 隔板仅使用独立PartCfg真空（现场为DO16），不使用破真空。
            if (PartCfg.Enable ~= true) then
                Alarm("La ventouse d’intercalaire n’est pas activée !", ErrorMessage.Type.WorkingDataErr)
                return
            end

            IORes(PartCfg.Port.Mode, PartCfg.Port.A, OFF)
            Wait(Time.Place.In)
            UpdatePayloadAfterRelease()
        end
    }

    local switch_mode = SwitchCloseSucker[CPoint.Paras.Mode]
    if switch_mode then
        switch_mode()
        LogInfo("Désactivation de la ventouse réussie !")
    else
        Alarm("Erreur CloseSucker. Veuillez vérifier la ventouse !", ErrorMessage.Type.WorkingDataErr)
    end
end
