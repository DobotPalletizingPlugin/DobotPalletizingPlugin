        end,
        [LiftingType.LINAK] = function()
            LogInfo("Création du client Modbus réussie !")
            LINAKInit()
            CurrentHeight = LINAKGetPostion()
            if CurrentHeight == nil then
                Err = 1
            else
                CurrentHeight = 0.1 * CurrentHeight
            end
        end
    }

    local switch_init_mode = SwitchCommInitMode[Communication.Lifting.Mode]
    if switch_init_mode then
        switch_init_mode()
    else
        Alarm("switch_init_mode est incorrect !", ErrorMessage.Type.WorkingDataErr)
    end
    if Err == 0 then
        LogInfo("Connexion de communication réussie !")
    else
        Alarm("Échec de la connexion à la colonne élévatrice !", ErrorMessage.Type.LinkErr)
    end

    if (CurrentHeight == nil) then
        LogError("Hauteur de la colonne élévatrice : %s", tostring(CurrentHeight))
        Alarm("Erreur de données de la colonne élévatrice !", ErrorMessage.Type.LiftingDataErr)
    else
        LiftingHeight = math.ceil(CurrentHeight)
    end
    LogInfo("Initialisation de la colonne élévatrice réussie !")
end
