local function GetAdjustedPartitionPoint(PalletNumber, BasePoint)
    local AdjustedPoint = DeepCopy(BasePoint)
    if PalletNumber.Pallet == 1 then
        AdjustedPoint.pose[1] = AdjustedPoint.pose[1] - 1000
    end
    return AdjustedPoint
end
