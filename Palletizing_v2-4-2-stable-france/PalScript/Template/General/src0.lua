-- 本文件是真正执行机器人动作的主文件：初始化、取料、放料、隔板取放、吸盘开关、payload更新、回程和状态机循环都在这里。
-- 关键输入是src3生成的CPoint：CPoint.Paras描述当前动作类型，CPoint.MotionPoint保存取料点/放料点/过渡点。
-- 常见条件说明：
-- 1. CPoint.Paras.Mode == MotionType.Norm：当前动作是普通箱子；MotionType.Part：当前动作是隔板。
-- 2. PalletNumber.Mode == WorkType.Pallet：码垛，把输送线箱子放到托盘；WorkType.Depallet：拆垛，把托盘箱子取走。
-- 3. CPoint.Paras.Sucker == -1：n吸n单放，通常一次吸多个箱子，然后按CIndex逐个放下。
-- 4. CIndex：当前正在处理第几个箱子/第几次放置；在n吸n单放中会影响剩余payload和释放哪一路吸盘。
-- 5. LDAcc/LDVel：带载速度参数；NLDAcc/NLDVel：空载速度参数；PlaceAcc/PlaceSpeed：贴近放置点的速度参数。
-- Motion execution file bilingual comment guide
-- This is the main runtime file that executes robot motion: initialization, pick, place, partition handling, sucker control, payload update, return motion, and state-machine loops.
-- The key input is CPoint generated by src3: CPoint.Paras describes the current process mode, while CPoint.MotionPoint stores pick/place/transition points.
-- Common condition meanings:
-- 1. CPoint.Paras.Mode == MotionType.Norm means the current motion is for normal boxes; MotionType.Part means the current motion is for partitions/interlayers.
-- 2. PalletNumber.Mode == WorkType.Pallet means palletizing from conveyor to pallet; WorkType.Depallet means depalletizing from pallet to output.
-- 3. CPoint.Paras.Sucker == -1 means multi-pick and single-place: the robot picks multiple boxes and releases them one by one according to CIndex.
-- 4. CIndex is the current box/place index. In multi-pick single-place, it controls remaining payload and which sucker channel should be released.
-- 5. LDAcc/LDVel are loaded motion parameters; NLDAcc/NLDVel are unloaded motion parameters; PlaceAcc/PlaceSpeed are used near the final placement point.
---------------------------------------------------------------
